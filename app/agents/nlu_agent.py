"""NLU: intent/entity extraction, clarification, suggested_worker.

The prompt stays minimal by design: company-name/symbol resolution is done in
CODE (app.utils.brvm_companies.normalize_entities), not by the model reading a
47-company list on every message. The model only copies the mention as written."""
from __future__ import annotations

import json
import logging
import re
from typing import Any

from langchain_core.messages import AIMessage, HumanMessage, SystemMessage

logger = logging.getLogger(__name__)
from app.models.llm import get_llm

from app.utils.brvm_companies import normalize_entities

from app.agents.utils import get_time_prefix


# Valid routing targets. "general" = no data, no specialist worker: greetings,
# chitchat, finance/BRVM education (handled by the general responder node).
VALID_WORKERS = frozenset({
    "scraper", "analytics", "timeseries", "charts", "news", "portfolio",
    "prediction", "sgi", "company_details", "advisor", "general",
})

# Pure greetings/chitchat: routed deterministically, WITHOUT an LLM call.
# Weak models keep misclassifying these (especially with a pending bot
# question in the history), and there is nothing to extract from them anyway.
# The reply itself is still model-generated by the general responder.
_GREETINGS = frozenset({
    "hi", "hello", "hey", "salut", "slt", "bonjour", "bjr", "bonsoir", "bsr",
    "coucou", "yo", "salam", "merci", "merci beaucoup", "good morning",
    "good evening", "good afternoon", "ca va", "comment ca va",
    "comment tu vas", "comment vas tu", "comment allez vous", "how are you",
})


def _is_pure_greeting(text: str) -> bool:
    """True when the message is ONLY a greeting/thanks (accents, case and
    punctuation ignored). 'salut, quel est le cours de SNTS ?' is NOT one."""
    import unicodedata

    t = "".join(
        c for c in unicodedata.normalize("NFKD", (text or "").lower())
        if not unicodedata.combining(c)
    )
    t = re.sub(r"[!?.,;…]+", " ", t)
    t = re.sub(r"\s+", " ", t).strip()
    return t in _GREETINGS

# Near-miss labels the model sometimes emits; normalized before validation.
_WORKER_ALIASES = {
    "scrape": "scraper",
    "chart": "charts",
    "company": "company_details",
    "company_detail": "company_details",
    "advice": "advisor",
    "finish": "general",
    "none": "general",
}

# Deterministic intent -> worker fallback (used when the model omits or
# misspells suggested_worker). Never default to a data worker blindly.
_INTENT_WORKER = {
    "market_overview": "analytics",
    "price_query": "analytics",
    "compare": "analytics",
    "metrics": "analytics",
    "chart": "charts",
    "news": "news",
    "prediction": "prediction",
    "scrape": "scraper",
    "update_timeseries": "timeseries",
    "portfolio_display": "portfolio",
    "portfolio_add": "portfolio",
    "portfolio_remove": "portfolio",
    "tracking_list": "portfolio",
    "tracking_add": "portfolio",
    "target_set": "portfolio",
    "target_list": "portfolio",
    "sgi": "sgi",
    "company_details": "company_details",
    "advice": "advisor",
    "brvm_basics": "general",
    "general": "general",
}


def _nlu_system_prompt() -> str:
    return f"""BRVM stock assistant NLU. Output CLARIFY or JSON only. F CFA. {get_time_prefix()}

**Context:** recent turns precede the CURRENT user message — resolve follow-ups, pronouns ("celle-là", "son cours") and bare values (symbol, date, price) against them: a bare value answering a bot question continues that question's intent (portfolio_add, chart...). Only a clearly new topic is treated independently.

**Rules:**
- Copy symbol/company mentions AS WRITTEN into entities.symbol (validated downstream). NEVER invent a symbol — if the question needs one but names none, CLARIFY. Another exchange than BRVM → CLARIFY.
- Greetings, chitchat, finance/BRVM education (what is a dividend, how the stock market works, c'est quoi la BRVM, how to invest) → intent general: NO data, NO worker needed. A greeting is ALWAYS general, even after a pending bot question.
- Market-level questions about NO specific company ("plus petite/moins chère/plus chère action", "palmarès", "top volumes", "market summary") → intent market_overview, worker analytics, entities {{}} — do NOT ask for a symbol.
- The user's own data ("mon portefeuille", "ma liste de suivi", "mes alertes") → portfolio_display | tracking_list | target_list, worker portfolio — NO symbol needed.
- How-to questions about this assistant (portfolio, tracking list, price alerts) → CLARIFY: a short explanation (2-3 sentences: how it works, what info is needed) + a follow-up question inviting the user to do it now.
- Compound request with ALL details given → output the intents directly (multi: "suggested_worker": "analytics,news", max 2).
- CLARIFY questions are short and in FRENCH.

**Intent → suggested_worker:** market_overview|price_query|compare|metrics → analytics · chart → charts · news → news · prediction → prediction · scrape → scraper · update_timeseries → timeseries · portfolio_display|portfolio_add|portfolio_remove|tracking_list|tracking_add|target_set|target_list → portfolio · sgi → sgi · company_details → company_details · advice → advisor · general|brvm_basics → general

**Output (one line, nothing else):** if unclear → CLARIFY: <short question in French> · otherwise exactly one JSON object, e.g. {{"intent": "price_query", "entities": {{"symbol": "NTLC"}}, "suggested_worker": "analytics"}}"""


def _extract_user_text(messages: list) -> str:
    for m in reversed(messages):
        if isinstance(m, HumanMessage) and m.content:
            return str(m.content).strip()
    return ""


def _resolve_worker(raw: str) -> str | None:
    """Normalize a single worker label; None when unknown."""
    norm = re.sub(r"\s+", "_", (raw or "").strip().lower())
    norm = _WORKER_ALIASES.get(norm, norm)
    return norm if norm in VALID_WORKERS else None


def _worker_for(intent: str, raw_worker: str) -> tuple[str, list[str]]:
    """Resolve (worker, multi_workers) from NLU output.

    Multi mode only when suggested_worker is labels joined by , or | (max 2;
    general/timeseries are never auto-chained). Missing/invalid label →
    deterministic intent map; last resort → general (never a data worker).
    """
    raw = (raw_worker or "").strip()
    if "," in raw or "|" in raw:
        seen: list[str] = []
        for part in re.split(r"[,|]", raw):
            w = _resolve_worker(part)
            if w and w not in ("general", "timeseries") and w not in seen:
                seen.append(w)
        if len(seen) >= 2:
            return "", seen[:2]
        if len(seen) == 1:
            return seen[0], []
    w = _resolve_worker(raw)
    if w:
        return w, []
    mapped = _INTENT_WORKER.get((intent or "").strip().lower())
    if mapped:
        return mapped, []
    return "general", []


_CLARIFY_RE = re.compile(r"CLARIFY\s*:\s*(.+)", re.IGNORECASE)


def _clean_clarification(text: str) -> str | None:
    """Reject junk clarifications: template echoes ("<question>") and one-word
    stubs some models emit instead of a real question."""
    t = (text or "").strip().strip("\"' ").splitlines()[0].strip()
    if len(t) < 12 or "<" in t or ">" in t:
        return None
    return t


def _parse_nlu_response(content: str) -> tuple[dict[str, Any] | None, str | None]:
    text = (content or "").strip()

    def _make_structured(intent: str, entities: dict, raw_worker: str) -> tuple[dict[str, Any], str | None]:
        # Resolve and validate symbols against BRVM list; ask for clarification if unknown
        entities, unknown = normalize_entities(entities)
        if unknown:
            return (
                None,
                f"Société ou symbole introuvable sur la BRVM : {', '.join(unknown)}. Utilisez un symbole de la liste BRVM (ex. NTLC, SLBC, SNTS, Sonatel, Solibra, Nestlé).",
            )
        worker, multi_workers = _worker_for(intent, raw_worker)
        structured: dict[str, Any] = {
            "intent": intent,
            "entities": entities,
            "suggested_worker": worker,
        }
        if multi_workers:
            structured["multi_workers"] = multi_workers
        return structured, None

    def _from_dict(data: dict) -> tuple[dict[str, Any], str | None] | None:
        if not isinstance(data, dict) or "intent" not in data:
            return None
        intent = data.get("intent") or "general"
        entities = data.get("entities") if isinstance(data.get("entities"), dict) else {}
        return _make_structured(intent, entities, data.get("suggested_worker") or "")

    for candidate in (text.strip(), re.sub(r"^.*?(\{)", r"\1", text, count=1)):
        try:
            parsed = _from_dict(json.loads(candidate))
            if parsed:
                return parsed
        except json.JSONDecodeError:
            pass
    # Find first { and match balanced braces
    start = text.find("{")
    if start >= 0:
        depth = 0
        for i, c in enumerate(text[start:], start=start):
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0:
                    try:
                        parsed = _from_dict(json.loads(text[start : i + 1]))
                        if parsed:
                            return parsed
                    except json.JSONDecodeError:
                        pass
                    break
    # Bare label output ("general", "FINISH") — some models answer with just
    # the route instead of the JSON object.
    if _resolve_worker(text) == "general" or text.strip().upper() == "FINISH":
        return {"intent": "general", "entities": {}, "suggested_worker": "general"}, None
    # CLARIFY anywhere (models often prefix it, e.g. "A) CLARIFY: ..." or
    # "unclear → CLARIFY: ..."). Junk/empty clarifications fall through.
    m = _CLARIFY_RE.search(text)
    if m:
        clarification = _clean_clarification(m.group(1))
        if clarification:
            return None, clarification
    # Unparseable: fall back to the general responder (it can still greet,
    # explain and redirect) instead of a dead-end "please reformulate" loop.
    logger.warning("[NLU] unparseable output, routing to general: %r", text[:300])
    return {"intent": "general", "entities": {}, "suggested_worker": "general"}, None


def _history_for_nlu(messages: list) -> list:
    """Recent conversation turns for the NLU, excluding the current message and
    internal [NLU] routing notes."""
    history = []
    for m in messages[:-1]:
        if isinstance(m, AIMessage) and "[NLU]" in str(getattr(m, "content", "") or ""):
            continue
        if isinstance(m, (HumanMessage, AIMessage)) and getattr(m, "content", None):
            history.append(m)
    return history[-10:]


def run_nlu_node(state: dict, model: str) -> dict:
    logger.info("[GRAPH] node=nlu start")
    messages = state.get("messages") or []
    user_text = _extract_user_text(messages)
    if not user_text:
        return {
            "messages": messages,
            "clarification": "What would you like to know about BRVM stocks?",
            "structured_data": None,
        }

    # Routing is a classification task: always temperature 0, whatever the
    # deployment's LLM_TEMPERATURE (sampling here caused malformed outputs).
    #
    # Pure greetings skip the classifier entirely: deterministic, instant,
    # and immune to weak models re-asking a pending question from history.
    if _is_pure_greeting(user_text):
        logger.info("[NLU] pure greeting, no LLM call: %r", user_text[:60])
        summary = "[NLU] intent=general, entities={}, suggested_worker=general"
        return {
            "messages": list(messages) + [AIMessage(content=summary)],
            "structured_data": {"intent": "general", "entities": {}, "suggested_worker": "general"},
            "clarification": None,
        }

    llm = get_llm(model=model, temperature=0.0)

    system = _nlu_system_prompt()
    # Give the NLU the recent conversation so it can resolve follow-ups
    # (e.g. a bare "ETIT" answering "which stock do you want to add?").
    history = _history_for_nlu(messages)
    prompt_messages = [SystemMessage(content=system)] + history + [
        HumanMessage(content=f"Current user message: {user_text}")
    ]
    reply = llm.invoke(prompt_messages)
    content = reply.content if hasattr(reply, "content") else str(reply)
    logger.info("[NLU] raw reply: %r", str(content)[:300])
    structured_data, clarification = _parse_nlu_response(content)

    if clarification:
        # Echo junk: some models parrot the user message back as the
        # "clarifying question" — answer via the general responder instead.
        _norm = lambda s: re.sub(r"[^\w\s]", "", (s or "").lower()).split()
        if _norm(clarification) == _norm(user_text):
            logger.warning("[NLU] clarification echoes the user message; routing to general: %r", clarification[:120])
            clarification = None
            structured_data = {"intent": "general", "entities": {}, "suggested_worker": "general"}
        else:
            return {
                "messages": messages,
                "clarification": clarification,
                "structured_data": None,
            }

    summary = f"[NLU] intent={structured_data.get('intent')}, entities={structured_data.get('entities')}, suggested_worker={structured_data.get('suggested_worker')}"
    new_messages = list(messages) + [AIMessage(content=summary)]

    return {
        "messages": new_messages,
        "structured_data": structured_data,
        "clarification": None,
    }


def create_nlu_node(model: str):
    def node(state: dict) -> dict:
        return run_nlu_node(state, model)

    return node
